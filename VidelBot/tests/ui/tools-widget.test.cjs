const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const dir = path.resolve(__dirname, '../../plugins/widget/tools');
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const html = read('shell.html').replace('/*CSS*/', read('tools.css')).replace('/*JS*/', read('tools.js'));
let ready = 0;
const dom = new JSDOM(html, {runScripts:'dangerously', beforeParse(w) { w.TelegramWidget = {ready() {ready++}}; }});
const d = dom.window.document;
const click = selector => { const b = d.querySelector(selector); assert.ok(b, selector); b.click(); };
const tab = name => click(`[data-tab="${name}"]`);
const key = name => click(`[data-key="${name}"]`);
const action = name => click(`[data-action="${name}"]`);
const value = () => d.getElementById('value').textContent;
for (const n of '100') key(n);
assert.equal(value(), '110.00 each');
action('people'); assert.equal(value(), '55.00 each');
action('tip'); assert.equal(value(), '57.50 each');
tab('convert'); for (const n of '10') key(n);
assert.equal(value(), '6.2137 mi');
action('swap'); assert.equal(value(), '16.0934 km');
action('unit'); action('unit'); key('clear'); for (const n of '40') key(n); action('sign');
assert.equal(value(), '-40 °F'); action('swap'); assert.equal(value(), '-40 °C');
tab('count'); action('plus'); action('plus'); action('minus'); assert.equal(value(), '1'); action('reset'); assert.equal(value(), '0');
assert.equal(ready, 1);
dom.window.close();
console.log('tools widget: split bill, conversion and counter passed');
